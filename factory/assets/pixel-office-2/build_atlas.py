"""Rebuild the coordinate atlas from the untouched user-supplied 768x512 PNG.
Requires Pillow. No resampling or generated artwork; strips contaminated alpha.
"""
import json
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parent
ROLES = ['intake','spec-writer','builder','review-security','review-ux','review-ui','review-code','approver']
BOXES = {
    'intake': (14,29,23,34), 'spec-writer': (72,29,23,34),
    'builder': (123,29,24,34), 'review-security': (175,29,23,34),
    'review-ux': (226,29,24,34), 'review-ui': (282,62,23,33),
    'review-code': (333,29,23,34), 'approver': (386,29,24,34),
    'desk': (8,132,66,47), 'deskDual': (146,132,69,47),
    'deskPlant': (77,132,65,47), 'sofaBlue': (13,182,52,35),
    'sofaGreen': (70,182,52,35), 'table': (155,182,46,35),
    'meetingTable': (104,223,51,45), 'plant': (204,179,27,43),
    'plantTall': (407,220,27,48), 'shelf': (527,135,44,50),
    'server': (616,134,26,52), 'vending': (580,134,29,51),
    'cooler': (583,184,27,43), 'board': (415,135,56,47),
    'chair': (126,181,27,35), 'printer': (491,224,29,44),
    'window': (168,277,53,39), 'wall': (230,278,77,37),
    'door': (194,321,28,40), 'floorWood': (260,369,29,31),
    'floorTile': (14,370,31,31), 'cabinet': (321,278,58,40),
}
source=Image.open(ROOT/'PixelOfficeAssets.png').convert('RGBA')
assert source.size == (768,512), 'Use the original-resolution source PNG'
# The supplied sheet has colored RGB in transparent pixels and alpha 1..17
# fringes. Binary alpha preserves crisp source pixels without neon halos.
clean=Image.new('RGBA', source.size)
clean.putdata([(r,g,b,255) if a >= 200 else (0,0,0,0) for r,g,b,a in source.getdata()])
clean.save(ROOT/'office-atlas.png')
sprites={k:dict(zip(['x','y','w','h'],v)) for k,v in BOXES.items()}
manifest={'source':'PixelOfficeAssets.png','image':'office-atlas.png','sourceSize':{'width':768,'height':512},
 'alphaThreshold':200,'sprites':sprites,'characters':{k:k for k in ROLES},
 'substitutions':['UI uses its intact side-facing pose because the front/back hat pixels are incomplete.',
 'A single complete standing pose per role is used; walking is translation with a one-pixel bob, not invented animation frames.',
 'The meeting table reuses the supplied rectangular coffee table at proportional scale; no occupied desk sprites are used.']}
(ROOT/'atlas.json').write_text(json.dumps(manifest,indent=2)+'\n')
(ROOT.parent.parent/'sprite-atlas.js').write_text('// Generated by assets/pixel-office-2/build_atlas.py. Source coordinates, never a background image.\n'
 + 'export const ATLAS_URL = new URL(\'./assets/pixel-office-2/office-atlas.png\', import.meta.url).href;\n'
 + 'export const SPRITES = Object.freeze('+json.dumps(sprites,indent=2)+');\n'
 + 'export const CHARACTER_FOR = Object.freeze('+json.dumps(manifest['characters'],indent=2)+');\n')
